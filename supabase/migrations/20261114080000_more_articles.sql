Many children say "I don't want to read" at some point. Usually reading is either too hard, or not yet enjoyable. Try this:

- **Let your child choose.** Comics, animal facts, sports books, recipes or joke books all count. Reading about something your child loves makes the biggest difference.
- **Take turns.** You read one sentence or page, your child the next. It feels less like work.
- **Choose easier books.** A book that's slightly too easy builds fluency and confidence. Success makes them want more.
- **Don't use reading as punishment.** Reading should be a nice time together, not a chore.
