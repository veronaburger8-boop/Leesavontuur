## What you can do at home

- **Read together a little every day.** Ten to fifteen minutes every day helps more than one long session a week.
- **Read the same passage again.** Reading a short passage two or three times makes it smoother and builds confidence.
- **Sound out words together.** Point with your finger, say the sounds slowly and blend them.
- **Read aloud to your child.** It builds vocabulary, shows what fluent reading sounds like, and keeps reading enjoyable.
- **Talk about the story.** Ask: "What do you think will happen next?" or "Why did he do that?" Understanding is the point of reading.
