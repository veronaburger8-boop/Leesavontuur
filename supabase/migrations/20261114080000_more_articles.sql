- **The same time every day.** After supper, before bath time or before bed: a fixed time quickly becomes part of the day.
- **A calm spot.** Switch off the television and put phones away. A comfortable corner with good light helps.
- **Keep it short and enjoyable.** Stop before your child gets tired or frustrated. It's better to finish while they still want more.
