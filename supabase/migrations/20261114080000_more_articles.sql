## A simple 15-minute routine

Split the time into three short parts:

- **Five minutes: you read aloud.** Choose something your child enjoys, even a little harder than they can read alone. They hear new words and what fluent reading sounds like.
- **Five minutes: your child reads.** Let them read something they already know or that's only a little challenging. Re-reading a familiar passage is excellent practice.
- **Five minutes: talk.** What was the best part? What would you have done? Was there a new word? Talking makes reading meaningful.

